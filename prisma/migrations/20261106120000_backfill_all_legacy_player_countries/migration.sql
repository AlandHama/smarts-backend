-- Backfill ISO values already written by newer clients.
UPDATE "PlayerProfile" AS p
SET "countryCode" = UPPER(TRIM(s."value"))
FROM "PlayerStorageItem" AS s
WHERE s."userId" = p."userId"
  AND s."key" = 'player_country'
  AND TRIM(s."value") ~ '^[A-Za-z]{2}$'
  AND (p."countryCode" IS NULL OR TRIM(p."countryCode") = '');

